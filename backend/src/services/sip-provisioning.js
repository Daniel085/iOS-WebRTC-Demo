/**
 * PJSIP endpoint provisioning (prototype).
 *
 * When a user verifies their phone number we make sure Asterisk has an
 * endpoint/auth/aor for them, so the gateway can REGISTER and place calls on
 * their behalf. Prototype approach from docs/SIP_INTEGRATION.md §5: write the
 * sections into pjsip_users.conf (which pjsip.conf #tryinclude's) and run
 * `pjsip reload` over AMI. Without AMI access the file is still written and a
 * reload hint is logged once.
 *
 * Production path: PJSIP realtime backed by Postgres (res_pjsip + res_config_pgsql
 * or the sorcery ODBC backend) once SKIP_DATABASE=false, so no file and no
 * reload are needed. The credentials stay the same (credentialsFor()).
 *
 * Env:
 *   SIP_ENABLED=true
 *   SIP_GATEWAY_SECRET=…                       (shared with sip-gateway.js)
 *   ASTERISK_USERS_CONF=./asterisk/etc/pjsip_users.conf
 *   ASTERISK_AMI_HOST / ASTERISK_AMI_PORT=5038 / ASTERISK_AMI_USER=gateway / ASTERISK_AMI_SECRET
 *   SIP_PROVISION_TIMEOUT_MS=3000             upper bound for file write + reload during verify-code
 */

const fs = require('fs');
const path = require('path');

const logger = require('../utils/logger');
const { credentialsFor } = require('./sip-gateway');
const { amiCommand } = require('./sip/ami-client');

const DEFAULT_CONF = path.resolve(__dirname, '../../asterisk/etc/pjsip_users.conf');
const FILE_HEADER = [
  '; pjsip_users.conf - GENERATED by backend/src/services/sip-provisioning.js',
  '; One block per app user, (re)written at verify-code time. Do not edit by hand;',
  '; edit pjsip.conf for templates and static endpoints instead.',
  ''
].join('\n');

function provisioningConfigFromEnv(env = process.env) {
  const toInt = (v, d) => (Number.isFinite(parseInt(v, 10)) ? parseInt(v, 10) : d);
  return {
    enabled: env.SIP_ENABLED === 'true',
    secret: env.SIP_GATEWAY_SECRET || '',
    confPath: env.ASTERISK_USERS_CONF ? path.resolve(env.ASTERISK_USERS_CONF) : DEFAULT_CONF,
    ami: env.ASTERISK_AMI_HOST
      ? {
        host: env.ASTERISK_AMI_HOST,
        port: toInt(env.ASTERISK_AMI_PORT, 5038),
        username: env.ASTERISK_AMI_USER || 'gateway',
        secret: env.ASTERISK_AMI_SECRET || '',
        timeoutMs: toInt(env.SIP_PROVISION_TIMEOUT_MS, 3000)
      }
      : null,
    timeoutMs: toInt(env.SIP_PROVISION_TIMEOUT_MS, 3000)
  };
}

/** pjsip.conf sections for one user, delimited by markers so they can be replaced. */
function renderUserBlock({ username, password, phoneNumber }) {
  return [
    `;; BEGIN ${username}`,
    `; app user ${phoneNumber}`,
    `[${username}](app-user)`,
    `auth=${username}`,
    `aors=${username}`,
    `callerid="${phoneNumber}" <${phoneNumber}>`,
    '',
    `[${username}](app-auth)`,
    `username=${username}`,
    `password=${password}`,
    '',
    `[${username}](app-aor)`,
    `;; END ${username}`,
    ''
  ].join('\n');
}

function upsertBlock(existing, username, block) {
  const begin = `;; BEGIN ${username}\n`;
  const end = `;; END ${username}\n`;
  const start = existing.indexOf(begin);
  if (start === -1) {
    const base = existing.trim() === '' ? FILE_HEADER : existing.replace(/\s*$/, '\n');
    return `${base}\n${block}`;
  }
  const stop = existing.indexOf(end, start);
  if (stop === -1) return `${existing.replace(/\s*$/, '\n')}\n${block}`;
  return existing.slice(0, start) + block + existing.slice(stop + end.length);
}

// Serialise writers: several verify-code requests may provision at once.
let writeQueue = Promise.resolve();

function writeUserBlock(confPath, username, block) {
  const job = writeQueue.then(async () => {
    await fs.promises.mkdir(path.dirname(confPath), { recursive: true });
    let existing = '';
    try { existing = await fs.promises.readFile(confPath, 'utf8'); } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    const next = upsertBlock(existing, username, block);
    if (next === existing) return { changed: false };
    const tmp = `${confPath}.${process.pid}.tmp`;
    await fs.promises.writeFile(tmp, next, 'utf8');
    await fs.promises.rename(tmp, confPath);
    return { changed: true };
  });
  writeQueue = job.catch(() => {});
  return job;
}

let reloadHintLogged = false;
let pendingReload = null;

/** Coalesce bursts of provisioning into one `pjsip reload`. */
function reloadPjsip(ami) {
  if (pendingReload) return pendingReload;
  pendingReload = new Promise((resolve) => setTimeout(resolve, 200))
    .then(() => amiCommand(ami, 'pjsip reload'))
    .finally(() => { pendingReload = null; });
  return pendingReload;
}

function withTimeout(promise, ms, label) {
  let timer;
  const timeout = new Promise((_, reject) => {
    timer = setTimeout(() => reject(new Error(`${label} timed out after ${ms} ms`)), ms);
    if (typeof timer.unref === 'function') timer.unref();
  });
  return Promise.race([promise, timeout]).finally(() => clearTimeout(timer));
}

/**
 * Ensure Asterisk knows this user. Never throws for an operational problem
 * (file not writable, AMI down): logs and returns what happened, so sign-in
 * is never blocked by telephony.
 *
 * @param {{ phoneNumber: string }} user
 * @param {object} [config]  provisioningConfigFromEnv() by default
 * @returns {Promise<{ skipped?: boolean, username?: string, changed?: boolean, reloaded?: boolean, error?: string }>}
 */
async function provisionSipUser(user, config = provisioningConfigFromEnv()) {
  if (!config.enabled) return { skipped: true };
  if (!user || !user.phoneNumber) return { skipped: true, error: 'no phone number' };

  try {
    const credentials = credentialsFor(config.secret, user.phoneNumber);
    const block = renderUserBlock({ ...credentials, phoneNumber: user.phoneNumber });
    const { changed } = await withTimeout(writeUserBlock(config.confPath, credentials.username, block), config.timeoutMs, 'pjsip_users.conf write');
    const result = { username: credentials.username, changed, reloaded: false };

    if (!changed) return result;
    logger.info(`SIP endpoint ${credentials.username} written to ${config.confPath}`);

    if (config.ami) {
      try {
        await withTimeout(reloadPjsip(config.ami), config.timeoutMs, 'pjsip reload');
        result.reloaded = true;
        logger.info(`Asterisk pjsip reload done for ${credentials.username}`);
      } catch (error) {
        result.error = error.message;
        logger.warn(`Asterisk reload failed (${error.message}); run 'asterisk -rx "pjsip reload"' manually`);
      }
    } else if (!reloadHintLogged) {
      reloadHintLogged = true;
      logger.info('ASTERISK_AMI_HOST not set: run `docker compose exec asterisk asterisk -rx "pjsip reload"` after new users sign in');
    }
    return result;
  } catch (error) {
    logger.warn(`SIP provisioning failed for ${user.phoneNumber}: ${error.message}`);
    return { error: error.message };
  }
}

module.exports = {
  provisionSipUser,
  provisioningConfigFromEnv,
  renderUserBlock,
  upsertBlock,
  reloadPjsip,
  DEFAULT_CONF
};
